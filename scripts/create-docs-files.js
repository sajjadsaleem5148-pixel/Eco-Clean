// ---- Verification ----
const SRV = "mongodb" + "+srv://";
const PLAIN = "mongodb" + "://";
const romanUrdu = /\b(nahi|karein|banayen|ho raha|poora naam|kam az kam)\b/i;
let failed = 0;
console.log("\nVerification:");
written.forEach((f) => {
  const src = fs.readFileSync(f, "utf8");
  const problems = [];
  if (!src.trim()) problems.push("empty");
  if (src.includes(SRV) || src.includes(PLAIN)) problems.push("contains a database address");
  if (/AUTH_SECRET=[A-Za-z0-9+\/=]{20,}/.test(src)) problems.push("looks like a real secret");
  if (romanUrdu.test(src)) problems.push("Roman Urdu present");
  if (src.includes("PlaceholderPage")) problems.push("placeholder text");
  if (problems.length > 0) {
    console.log(" FAIL (" + problems.join(", ") + "): " + f);
    failed++;
  } else {
    console.log(" OK: " + f);
  }
});

if (failed > 0) {
  console.error("\nFAILED: " + failed + " file(s) need attention.");
  process.exit(1);
}

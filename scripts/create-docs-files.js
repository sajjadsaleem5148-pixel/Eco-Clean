// Existing README is saved first. An older backup is never overwritten.
const backupDir = "scripts/backup-docs";
fs.mkdirSync(backupDir, { recursive: true });
if (fs.existsSync("README.md")) {
  const backup = path.join(backupDir, "README.md.bak");
  if (!fs.existsSync(backup)) {
    fs.copyFileSync("README.md", backup);
    console.log("Backup:", backup);
  }
}

const written = [];

function doc(file, lines) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, lines.join("\n") + "\n", "utf8");
  written.push(file);
  console.log("Written:", file);
}

